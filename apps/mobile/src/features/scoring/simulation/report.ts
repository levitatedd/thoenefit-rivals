import { RULES_V1 } from '../rules';
import {
  capAndComebackExample,
  DURATIONS,
  goalAmbition,
  missedDays,
  mixedFitness,
  rawTotalsBaseline,
  REPORT_RUNS,
  tieRate,
} from './scenarios';
import { PROFILES } from './profiles';
import { statsOf } from './simulate';

/**
 * Renders docs/SCORING-VALIDATION.md from the scenario catalogue. Regenerate with
 * `npm run simulate:report` (apps/mobile). Fully deterministic: same code → same report.
 */

const pct = (x: number) => `${(100 * x).toFixed(1)}%`;
const fair = (players: number) => pct(1 / players);
const row = (cells: (string | number)[]) => `| ${cells.join(' | ')} |`;

export function renderReport(): string {
  const out: string[] = [];
  const w = (line = '') => out.push(line);
  const F = RULES_V1.fairness;

  // ------------------------------------------------------------------ data
  const mixed = Object.fromEntries(DURATIONS.map((d) => [d, mixedFitness(d)]));
  const mixedCalories = mixedFitness(7, 'calorie-clash');
  const raw = Object.fromEntries(DURATIONS.map((d) => [d, rawTotalsBaseline(d)]));
  const factors = [0.5, 0.7, 0.85, 1, 1.3];
  const ambition = factors.map((f) => ({
    f,
    byDays: DURATIONS.map((d) => statsOf(goalAmbition(f, d), 'tested')),
  }));
  const missed = [3, 7].map((d) => ({
    d,
    none: statsOf(missedDays(d, 0), 'tested').winShare,
    one: statsOf(missedDays(d, 1), 'tested').winShare,
    oneBig2: statsOf(missedDays(d, 1, 2), 'tested').winShare,
    oneBig3: statsOf(missedDays(d, 1, 3), 'tested').winShare,
    two: d >= 3 ? statsOf(missedDays(d, 2), 'tested').winShare : NaN,
  }));
  const ties = [1, 0.7, 0.5, 0.4].map((f) => ({
    f,
    byDays: DURATIONS.map((d) => tieRate(d, f).firstPlaceTieRate),
  }));
  const example = capAndComebackExample();
  const at = (f: number, d: number) =>
    ambition.find((a) => a.f === f)!.byDays[DURATIONS.indexOf(d as 1 | 3 | 7)];

  // ------------------------------------------------------------------ header
  w('# Scoring validation with simulated competitions (#14)');
  w();
  w(
    `Generated by \`npm run simulate:report\` (apps/mobile) from \`src/features/scoring/simulation\`. ` +
      `Every number below comes from the real v1 scoring engine (#2) applied to **synthetic, seeded** ` +
      `activity — no real people, devices or health data. ${REPORT_RUNS} simulated competitions per scenario; ` +
      `re-running produces exactly the same report. No scoring rules were changed for this analysis.`,
  );
  w();
  w('## Set-up');
  w();
  w(
    '- Rules: `v1` — daily points = min(200, 100 × activity ÷ personal goal), summed over days; 0.01-point precision; ties share a place.',
  );
  w(
    '- Each simulated day is a platform daily total drawn around the player’s typical day with ±30% day-to-day variation (log-normal).',
  );
  w('- Fitness levels (typical day):');
  for (const p of Object.values(PROFILES)) {
    w(
      `  - **${p.label}**: ${p.mean.steps.toLocaleString('en-US')} steps / ${p.mean.activeEnergyKcal} active kcal`,
    );
  }
  w(
    '- "Goal factor" = personal goal ÷ the player’s typical day (1.0 = honest, 0.5 = half their usual day).',
  );
  w(
    `- Fairness advice uses each player’s synthetic 28-day history and the configured bands: < ${Math.round(F.potentiallyEasyBelow * 100)}% potentially easy, < ${Math.round(F.belowUsualBelow * 100)}% below usual, ≤ ${Math.round(F.aboveUsualAbove * 100)}% near usual, above that above usual.`,
  );
  w('- "Win share" counts a shared first place as a fraction of a win, so shares add up to 100%.');
  w();

  // ------------------------------------------------------------------ 1
  w('## 1. Personal goals level different fitness levels');
  w();
  w(
    `Four players (light, moderate, active, athlete), everyone with an honest goal. A perfectly fair contest gives each ${fair(4)}.`,
  );
  w();
  w(
    row([
      'Win share',
      ...DURATIONS.map((d) => `${d}-day (personal goals)`),
      '7-day (one shared goal, ≈ raw totals)',
    ]),
  );
  w(row(['---', ...DURATIONS.map(() => '---:'), '---:']));
  for (const id of ['light', 'moderate', 'active', 'athlete']) {
    w(
      row([
        PROFILES[id as 'light'].label,
        ...DURATIONS.map((d) => pct(statsOf(mixed[d], id).winShare)),
        pct(statsOf(raw[7], id).winShare),
      ]),
    );
  }
  w();
  w(
    `Calorie Clash behaves the same (7-day win shares: ${['light', 'moderate', 'active', 'athlete']
      .map((id) => pct(statsOf(mixedCalories, id).winShare))
      .join(' / ')}).`,
  );
  w();
  w(
    '**Finding:** goal-relative scoring works as intended — a light walker competes on equal terms with an athlete. Ranked by raw activity, the athlete would win almost every time. 1-day competitions are noisier (more luck), as expected.',
  );
  w();

  // ------------------------------------------------------------------ 2
  w('## 2. Goal ambition: easy, honest and ambitious goals');
  w();
  w(
    `One moderate player sets a goal at the given factor of their typical day; three moderate peers are honest. Fair share = ${fair(4)}.`,
  );
  w();
  w(
    row([
      'Goal factor',
      'Advice shown privately (most common)',
      ...DURATIONS.map((d) => `Win share ${d}-day`),
      'Days at cap (7-day)',
      'Future-goal suggestion (7-day)',
    ]),
  );
  w(row(['---', '---', ...DURATIONS.map(() => '---:'), '---:', '---:']));
  for (const a of ambition) {
    const seven = a.byDays[2];
    const band = Object.entries(seven.fairnessBands).sort((x, y) => y[1] - x[1])[0];
    w(
      row([
        `${a.f}`,
        `${band[0]} (${pct(band[1])})`,
        ...a.byDays.map((s) => pct(s.winShare)),
        pct(seven.cappedDayShare),
        pct(seven.suggestionRate),
      ]),
    );
  }
  w();
  w('**Findings:**');
  w();
  w(
    `- **Easy goals dominate.** At half their usual day a player wins ${pct(at(0.5, 1).winShare)} of 1-day and ${pct(at(0.5, 7).winShare)} of 7-day competitions against honest peers. The private warning fires ("potentially easy"), but by design it never affects points, so it does not change the outcome. The 200-point cap limits the advantage per day but does not neutralise it.`,
  );
  w(
    `- **Modestly easy goals still win often.** A goal at 85% of a typical day wins ${pct(at(0.85, 7).winShare)} of 7-day competitions — about ${(at(0.85, 7).winShare / 0.25).toFixed(1)}× a fair share. With the original 80–120% "near usual" band it was labelled *near usual*; the band is now ${Math.round(F.belowUsualBelow * 100)}–${Math.round(F.aboveUsualAbove * 100)}% (#31), so it is flagged *below usual* in ${pct(at(0.85, 7).fairnessBands['below-usual'] ?? 0)} of runs.`,
  );
  w(
    `- **Ambitious goals rarely win.** At 130% a player wins only ${pct(at(1.3, 7).winShare)} of 7-day competitions. The private advice now explains that a higher goal makes each point harder to earn (#31).`,
  );
  w(
    `- **The future-goal suggestion** (≥ 3 capped days in 7) catches very easy goals (${pct(at(0.5, 7).suggestionRate)} of 7-day competitions at 0.5) but almost never moderately easy ones (${pct(at(0.7, 7).suggestionRate)} at 0.7).`,
  );
  w('- Longer competitions amplify any goal advantage: small daily edges add up over 7 days.');
  w();

  // ------------------------------------------------------------------ 3
  w('## 3. Missed days and comeback potential');
  w();
  w(
    `One moderate player has confirmed zero days at the start of the competition; three honest moderate peers. Fair share = ${fair(4)}.`,
  );
  w();
  w(row(['Win share', '3-day', '7-day']));
  w(row(['---', '---:', '---:']));
  const m = (d: number) => missed.find((x) => x.d === d)!;
  w(row(['No missed days', pct(m(3).none), pct(m(7).none)]));
  w(row(['1 missed day', pct(m(3).one), pct(m(7).one)]));
  w(row(['1 missed day + one 2× day', pct(m(3).oneBig2), pct(m(7).oneBig2)]));
  w(row(['1 missed day + one 3× day (capped)', pct(m(3).oneBig3), pct(m(7).oneBig3)]));
  w(row(['2 missed days', pct(m(3).two), pct(m(7).two)]));
  w();
  w('Worked example (goal 10,000 steps, 7 days; exact, not random):');
  w();
  w(row(['Player', 'Daily steps', 'Daily points', 'Total', 'Rank']));
  w(row(['---', '---', '---', '---:', '---:']));
  for (const s of [example.comeback, example.steady, example.spike]) {
    w(
      row([
        s.participantId,
        s.days.map((d) => d.eligibleActivity.toLocaleString('en-US')).join(', '),
        s.days.map((d) => d.points).join(', '),
        s.totalPoints,
        s.rank ?? '–',
      ]),
    );
  }
  w();
  w('**Findings:**');
  w();
  w(
    '- **Comebacks are possible but bounded.** A missed day costs about one typical day (~100 points); one exceptional day can earn at most 100 points more than a typical day (the cap), so one big day can make up for one missed day, but not for two.',
  );
  w(
    '- **The cap works as intended.** The "spike" player’s 60,000-step day would be worth 600 points uncapped and win the week; capped at 200 it can’t outweigh consistent effort.',
  );
  w('- Short competitions are unforgiving: missing one day of three is very hard to recover from.');
  w();

  // ------------------------------------------------------------------ 4
  w('## 4. Ties');
  w();
  w(
    'Four moderate players, all with the same goal factor. Share of competitions where first place is shared:',
  );
  w();
  w(row(['Everyone’s goal factor', ...DURATIONS.map((d) => `${d}-day`)]));
  w(row(['---', ...DURATIONS.map(() => '---:')]));
  for (const t of ties) w(row([`${t.f}`, ...t.byDays.map(pct)]));
  w();
  w(
    '**Findings:** with realistic goals, exact ties for first are rare thanks to 0.01-point precision. When goals are very easy, players hit the 200-point cap together and **short competitions frequently end in ties** (by design, ties stay ties).',
  );
  w();

  // ------------------------------------------------------------------ recommendations
  w('## Decisions');
  w();
  w(
    'The owner reviewed these findings in #10 (`docs/PRIVACY-SECURITY.md`, decision D4). The points formula and the 200-point cap are unchanged.',
  );
  w();
  w(
    '1. **Keep the core formula.** Goal-relative points with a per-day cap level fitness differences, reward consistency, limit outlier days and still allow comebacks.',
  );
  w(
    `2. **Clearer private advice (done, #31):** "near usual" is now ${Math.round(F.belowUsualBelow * 100)}–${Math.round(F.aboveUsualAbove * 100)}%, and the advice explains that lower goals make points easier and higher goals make them harder.`,
  );
  w(
    '3. **Usual-day goals as the default competition mode, with neutral goal labels in casual mode (planned, #32):** goals start at each player’s own usual day and can only be raised; players with limited history choose their own goal and are never penalized.',
  );
  w('4. **Ties:** shared places stay, and the leaderboard explains them (done, #3).');
  w(
    '5. **Validate with real data later:** these simulations assume ±30% daily variation for everyone; real variability differs by person and device. Re-run with real (consented) aggregates when health integrations exist.',
  );
  w();
  w(
    'Owner decision on these options, with extra simulations (goals at 80–95% of a usual day): [PRIVACY-SECURITY.md → Easy goals](PRIVACY-SECURITY.md#5-easy-goals-options-for-a-decision) (#10).',
  );
  w();
  w('## Limitations');
  w();
  w(
    '- Synthetic data: invented fitness profiles and a simple day-to-day variation model; no weekly patterns, illness streaks or device gaps beyond the modelled missed days.',
  );
  w(
    '- Only platform daily totals are simulated, so eligibility edge cases (overlaps, held records) are covered by the unit tests in #2, not here.',
  );
  w('- Win shares are estimates from 400 runs (± about 2–4 percentage points).');
  w();
  return `${out.join('\n')}\n`;
}
